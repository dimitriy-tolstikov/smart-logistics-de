-- Params: start_date, end_date (window already materialised in core_load_staging)
INSERT INTO core.fact_prices (
    price_id,
    created_at,
    loading_date,
    end_loading_date,
    loading_city_gcid,
    unloading_city_gcid,
    distance,
    total_weight,
    total_volume,
    currency_code,
    price_original,
    price_rub,
    nearest_rate_date,
    price_type,
    is_fact,
    complex,
    outlier_mark,
    organization_id,
    subscriber_id,
    weight_category,
    volume_category,
    body_type_source,
    source_row_hash
)
SELECT
    c.price_id,
    c.created_at,
    c.loading_date,
    c.end_loading_date,
    c.loading_city_gcid,
    c.unloading_city_gcid,
    c.distance,
    c.total_weight,
    c.total_volume,
    c.currency_code,
    c.price_original,
    COALESCE(c.price_rub_conv, 0) AS price_rub,
    c.nearest_rate_date,
    c.price_type,
    c.is_fact,
    c.complex,
    c.outlier_mark,
    c.organization_id,
    c.subscriber_id,
    COALESCE(NULLIF(TRIM(c.source_weight_category), ''), c.weight_category_filled) AS weight_category,
    COALESCE(NULLIF(TRIM(c.source_volume_category), ''), c.volume_category_filled) AS volume_category,
    c.body_type_source,
    md5(
        concat_ws(
            '|',
            c.price_id::text,
            c.loading_date::text,
            c.loading_city_gcid::text,
            c.unloading_city_gcid::text,
            c.distance::text,
            c.total_weight::text,
            c.total_volume::text,
            c.currency_code,
            c.price_original::text,
            c.price_type::text,
            c.is_fact::text,
            c.complex::text,
            c.outlier_mark::text,
            COALESCE(c.organization_id::text, ''),
            COALESCE(c.subscriber_id::text, ''),
            COALESCE(c.nearest_rate_date::text, ''),
            COALESCE(c.body_type_source::text, '')
        )
    ) AS source_row_hash
FROM core_load_staging c
WHERE c.dq_status = 'ok' AND c.price_rub_conv IS NOT NULL;
